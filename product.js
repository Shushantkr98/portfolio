/* =========================================
   DISPLAY PRODUCTS
========================================= */

function displayProducts(list) {

    if (!productGrid) return;

    productGrid.innerHTML = "";

    if (!list.length) {

        productGrid.innerHTML = `
            <div class="no-products">
                <h3>No products found.</h3>
                <p>Try another category.</p>
            </div>
        `;

        if (productCount) {
            productCount.textContent = "0 PRODUCTS";
        }

        return;
    }

    if (productCount) {
        productCount.textContent = `${list.length} PRODUCTS`;
    }

    list.forEach(product => {

        const card =
            document.createElement("article");

        card.className = "product-card";

        card.dataset.id =
            String(product.id);

        card.innerHTML = `

            <div class="product-image">

                <span class="product-badge">
                    NEW
                </span>

                <button
                    class="wishlist"
                    data-id="${product.id}"
                    type="button"
                    aria-label="Add to wishlist"
                >
                    ♡
                </button>

                <img
                    src="${product.image}"
                    alt="${product.name}"
                    loading="lazy"
                    onerror="this.onerror=null; this.src='https://placehold.co/800x1000/f5f5f5/111111?text=Product';"
                >

                <button
                    class="quick-add"
                    data-id="${product.id}"
                    type="button"
                >
                    ADD TO BAG
                </button>

            </div>

            <div class="product-info">

                <div>

                    <h3>
                        ${product.name}
                    </h3>

                    <p>
                        ${product.description}
                    </p>

                </div>

                <strong>
                    ₹${product.price.toLocaleString("en-IN")}
                </strong>

            </div>

        `;

        productGrid.appendChild(card);

    });

    attachProductEvents();
}


/* =========================================
   PRODUCT CARD EVENTS
========================================= */

function attachProductEvents() {

    document
        .querySelectorAll(".product-card")
        .forEach(card => {

            card.addEventListener(
                "click",
                function (event) {

                    if (
                        event.target.closest(".wishlist") ||
                        event.target.closest(".quick-add")
                    ) {
                        return;
                    }

                    const productId =
                        this.dataset.id;

                    if (!productId) {
                        return;
                    }

                    window.location.href =
                        `product.html?id=${encodeURIComponent(productId)}`;

                }
            );

        });


    document
        .querySelectorAll(".wishlist")
        .forEach(button => {

            button.addEventListener(
                "click",
                function (event) {

                    event.preventDefault();
                    event.stopPropagation();

                    this.classList.toggle("active");

                    this.textContent =
                        this.classList.contains("active")
                            ? "♥"
                            : "♡";

                }
            );

        });


    document
        .querySelectorAll(".quick-add")
        .forEach(button => {

            button.addEventListener(
                "click",
                function (event) {

                    event.preventDefault();
                    event.stopPropagation();

                    const id =
                        Number(this.dataset.id);

                    const product =
                        allProducts.find(
                            item => item.id === id
                        );

                    if (!product) {
                        return;
                    }

                    addToCart(product);

                }
            );

        });

}


