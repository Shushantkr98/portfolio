/* =========================================
   UPDATE PRODUCTS
========================================= */

function updateProducts() {

    let filteredProducts =
        [...products];

    if (currentCategory !== "all") {

        filteredProducts =
            filteredProducts.filter(product => {

                return product.category
                    .toLowerCase()
                    .includes(
                        currentCategory.toLowerCase()
                    );

            });

    }

    if (sortSelect) {

        const sort =
            sortSelect.value;

        if (sort === "low") {

            filteredProducts.sort(
                (a, b) =>
                    a.price - b.price
            );

        }

        else if (sort === "high") {

            filteredProducts.sort(
                (a, b) =>
                    b.price - a.price
            );

        }

        else if (sort === "newest") {

            filteredProducts.sort(
                (a, b) =>
                    b.newest - a.newest
            );

        }

    }

    displayProducts(filteredProducts);

}


/* =========================================
   CART
========================================= */

function getCart() {

    try {

        return JSON.parse(
            localStorage.getItem("elanCart")
        ) || [];

    }

    catch (error) {

        return [];

    }

}


function saveCart(cart) {

    localStorage.setItem(
        "elanCart",
        JSON.stringify(cart)
    );

}


function addToCart(product) {

    const cart =
        getCart();

    const existing =
        cart.find(
            item =>
                item.id === product.id
        );

    if (existing) {

        existing.quantity =
            (existing.quantity || 1) + 1;

    }

    else {

        cart.push({

            id: product.id,

            name: product.name,

            price: product.price,

            image: product.image,

            category: product.category,

            size: "M",

            quantity: 1

        });

    }

    saveCart(cart);

    updateCartCount();

    showToast(
        `${product.name} added to bag ✓`
    );

}


/* =========================================
   CART COUNT
========================================= */

function updateCartCount() {

    const cart =
        getCart();

    const total =
        cart.reduce(
            (sum, item) =>
                sum + (item.quantity || 1),
            0
        );

    const counter =
        document.getElementById("cartCount");

    if (counter) {

        counter.textContent =
            total;

    }

}


/* =========================================
   TOAST
========================================= */

function showToast(message) {

    const toast =
        document.getElementById("toast");

    if (!toast) return;

    toast.textContent =
        message;

    toast.classList.add("show");

    setTimeout(
        () => {

            toast.classList.remove("show");

        },
        2200
    );

}


